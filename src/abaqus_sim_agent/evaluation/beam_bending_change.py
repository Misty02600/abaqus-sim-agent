class BeamBendingConvergenceMode(StrEnum):
    OFF = "off"
    PRODUCTION_FIRST_ODB_V1 = "production_first_odb_v1"
    VERIFIED_B31_ODB_CONTRACT_V1 = "verified_b31_odb_contract_v1"
    DECLARED_ODB_CONTRACT_V2 = "declared_odb_contract_v2"


def task_instructions(mode: BeamBendingConvergenceMode) -> str:
    if mode is BeamBendingConvergenceMode.OFF:
        return TASK_INSTRUCTIONS
    instructions = f"{TASK_INSTRUCTIONS}\n\n{PRODUCTION_FIRST_ODB_INSTRUCTIONS}"
    if mode is BeamBendingConvergenceMode.VERIFIED_B31_ODB_CONTRACT_V1:
        instructions = f"{instructions}\n\n{VERIFIED_B31_ODB_CONTRACT_INSTRUCTIONS}"
    return instructions


def change_request(mode: BeamBendingConvergenceMode) -> str:
    if mode is BeamBendingConvergenceMode.DECLARED_ODB_CONTRACT_V2:
        return DECLARED_CONTRACT_CHANGE_REQUEST
    return CHANGE_REQUEST


def prompt_version(mode: BeamBendingConvergenceMode) -> str:
    if mode is BeamBendingConvergenceMode.DECLARED_ODB_CONTRACT_V2:
        return DECLARED_CONTRACT_PROMPT_VERSION
    return PROMPT_VERSION


class _FrozenModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)


class BeamBendingChangeEvalInput(_FrozenModel):
    goal: str = CHANGE_REQUEST


class BeamBendingChangeEvalMetadata(_FrozenModel):
    source_run_id: str


class BeamBendingChangeObservation(_FrozenModel):
    run_id: str
    source_run_id: str
    outcome: CodingRunOutcome
    verification: BeamBendingChangeVerificationAttempt | None = None
    abaqus_runtime_seconds: float = Field(ge=0)


class BeamBendingChangeEvalGate(_FrozenModel):
    attempts: int = Field(ge=0)
    passes: int = Field(ge=0)
    required_passes: int = Field(ge=1)
    passed: bool


@dataclass
class BeamBendingChangeEvaluator(
    Evaluator[
        BeamBendingChangeEvalInput,
        BeamBendingChangeObservation,
        BeamBendingChangeEvalMetadata,
    ]
):
    def evaluate(
        self,
        ctx: EvaluatorContext[
            BeamBendingChangeEvalInput,
            BeamBendingChangeObservation,
            BeamBendingChangeEvalMetadata,
        ],
    ) -> dict[str, EvaluationReason | float | str]:
        output = ctx.output
        attempt = output.verification
        verification = attempt.verification if attempt is not None else None
        report = attempt.change_report if attempt is not None else None
        passed = (
            output.outcome.status is CodingRunStatus.COMPLETED
            and not output.outcome.clarifications
            and attempt is not None
            and attempt.passed
            and verification is not None
            and verification.new_requirement_passed
            and verification.regression_passed
            and report is not None
            and bool(report.build_model_patch)
            and bool(report.extract_results_patch)
        )
        return {
            "model_change_pass": EvaluationReason(
                value=passed,
                reason=(
                    "B31 transverse-load change and source regressions passed"
                    if passed
                    else "beam bending change failed at "
                    + (output.outcome.failure_stage or "verification")
                ),
            ),
            "new_requirement_score": (
                1.0
                if verification is not None and verification.new_requirement_passed
                else 0.0
            ),
            "regression_score": (
                1.0
                if verification is not None and verification.regression_passed
                else 0.0
            ),
            "diff_contract_score": (
                1.0
                if report is not None
                and bool(report.build_model_patch)
                and bool(report.extract_results_patch)
                else 0.0
            ),
            "failure_stage": output.outcome.failure_stage or "none",
        }


def build_dataset(
    source_run_id: str,
    *,
    goal: str = CHANGE_REQUEST,
) -> Dataset[
    BeamBendingChangeEvalInput,
    BeamBendingChangeObservation,
    BeamBendingChangeEvalMetadata,
]:
    return Dataset(
        name="abaqus2024_b31_bending_change_v1",
        cases=[
            Case(
                name="verified_b31_tip_load_y",
                inputs=BeamBendingChangeEvalInput(goal=goal),
                metadata=BeamBendingChangeEvalMetadata(source_run_id=source_run_id),
            )
        ],
        evaluators=[BeamBendingChangeEvaluator()],
    )


def gate_report(
    report: EvaluationReport[
        BeamBendingChangeEvalInput,
        BeamBendingChangeObservation,
        BeamBendingChangeEvalMetadata,
    ],
    *,
    repeat: int,
    required_passes: int,
) -> BeamBendingChangeEvalGate:
    cases = list(report.cases)
    passes = sum(_case_passed(case) for case in cases)
    attempts = len(cases) + len(report.failures)
    return BeamBendingChangeEvalGate(
        attempts=attempts,
        passes=passes,
        required_passes=required_passes,
        passed=attempts == repeat and passes >= required_passes,
    )


async def run_evaluation(
    run_root: Path,
    *,
    source_run_dir: Path,
    model_gateway: DeepSeekGateway = DeepSeekGateway.OPENCODE_GO,
    model_name: str = DEEPSEEK_V4_FLASH,
    http_retries: int = DEFAULT_MODEL_HTTP_RETRIES,
    repeat: int = 3,
    required_passes: int = 2,
    convergence_mode: BeamBendingConvergenceMode = BeamBendingConvergenceMode.OFF,
) -> BeamBendingChangeEvalGate:
    if repeat < 1:
        raise ValueError("repeat must be positive")
    if required_passes < 1 or required_passes > repeat:
        raise ValueError("required_passes must be between 1 and repeat")
    run_root = await asyncio.to_thread(run_root.resolve)
    seed = await asyncio.to_thread(
        load_verified_beam_seed,
        source_run_dir,
        forbidden_root=run_root,
    )
    harness_hash_patch = apply_harness_windows_newline_hash_patch()
    harness_shell_patch = apply_harness_windows_shell_tree_patch()
    api_key = take_gateway_api_key_from_environment(model_gateway)
    skill_digest = await asyncio.to_thread(
        sha256_file,
        skill_library_path() / "abaqus-2024-coding" / "SKILL.md",
    )
    resolved_task_instructions = task_instructions(convergence_mode)
    resolved_change_request = change_request(convergence_mode)
    resolved_prompt_version = prompt_version(convergence_mode)
    budget = CodingRunBudget(
        max_clarifications=0,
        max_model_requests=MODEL_REQUEST_BUDGET,
        max_api_lookup_calls=0,
        max_concept_lookup_calls=0,
        max_abaqus_calls=ABAQUS_CALL_BUDGET,
        max_solver_calls=SOLVER_CALL_BUDGET,
        wall_time_seconds=2_700.0,
    )
    metadata = {
        "model_gateway": model_gateway.value,
        "model": model_name,
        "base_url": gateway_base_url(model_gateway),
        "protocol": "openai-chat-completions",
        "profile_family": "pydantic-ai-deepseek",
        "thinking": "provider-default",
        "thinking_history_replay": (
            "disabled-go-compat"
            if model_gateway is DeepSeekGateway.OPENCODE_GO
            else "field"
        ),
        "http_retries": http_retries,
        "http_timeout_seconds": DEFAULT_MODEL_HTTP_TIMEOUT_SECONDS,
        "api_catalog_mode": "off",
        "concept_retrieval_mode": "off",
        "planning_enabled": False,
        "convergence_mode": convergence_mode.value,
        "task_instructions_sha256": hashlib.sha256(
            resolved_task_instructions.encode("utf-8")
        ).hexdigest(),
        "coder_general_shell_policy": CODER_GENERAL_SHELL_POLICY_VERSION,
        "source_run_id": seed.outcome.run_id,
        "source_request_sha256": seed.provenance.request_sha256,
        "source_outcome_sha256": seed.provenance.outcome_sha256,
        "source_verification_sha256": seed.provenance.verification_sha256,
        "source_artifact_sha256": seed.provenance.artifact_sha256,
        "skill_sha256": skill_digest,
        "pydantic_ai_version": version("pydantic-ai-slim"),
        "pydantic_ai_harness_version": version("pydantic-ai-harness"),
        "harness_windows_newline_hash_patch": harness_hash_patch,
        "harness_windows_shell_tree_patch": harness_shell_patch,
        "runtime": "Abaqus 2024",
        "prompt_version": resolved_prompt_version,
        "repeat": repeat,
        "required_passes": required_passes,
        "model_request_budget": MODEL_REQUEST_BUDGET,
        "abaqus_call_budget": ABAQUS_CALL_BUDGET,
        "solver_call_budget": SOLVER_CALL_BUDGET,
        "verify_on_budget_exhaustion": True,
    }

    async def run_case(
        inputs: BeamBendingChangeEvalInput,
    ) -> BeamBendingChangeObservation:
        result = await execute_model_change_case(
            run_root,
            seed=seed,
            goal=inputs.goal,
            run_id_prefix="beam-bending",
            verifier=BeamBendingChangeRunVerifier(
                source_run_id=seed.outcome.run_id,
                source_run_verified=True,
                seed_texts=seed.seed_texts,
            ),
            budget=budget,
            model_gateway=model_gateway,
            model_name=model_name,
            api_key=api_key,
            http_retries=http_retries,
            task_instructions=resolved_task_instructions,
            verify_on_budget_exhaustion=True,
        )
        usage = result.outcome.usage
        for name, value in {
            "model_requests": usage.model_requests,
            "input_tokens": usage.input_tokens,
            "output_tokens": usage.output_tokens,
            "tool_calls": usage.tool_calls,
            "abaqus_calls": usage.abaqus_calls,
            "solver_calls": usage.solver_calls,
            "abaqus_runtime_s": result.abaqus_runtime_seconds,
        }.items():
            increment_eval_metric(name, value)
        set_eval_attribute("run_id", result.run_id)
        set_eval_attribute("source_run_id", seed.outcome.run_id)
        set_eval_attribute("workspace", str(result.workspace))
        return BeamBendingChangeObservation(
            run_id=result.run_id,
            source_run_id=seed.outcome.run_id,
            outcome=result.outcome,
            verification=result.verification,
            abaqus_runtime_seconds=result.abaqus_runtime_seconds,
        )

    report = await build_dataset(
        seed.outcome.run_id,
        goal=resolved_change_request,
    ).evaluate(
        run_case,
        name=f"{model_gateway.value}-{model_name}-abaqus2024-{resolved_prompt_version}",
        repeat=repeat,
        max_concurrency=1,
        retry_task=None,
        retry_evaluators=None,
        metadata=metadata,
    )
    gate = gate_report(
        report,
        repeat=repeat,
        required_passes=required_passes,
    )
    _write_evaluation_artifacts(run_root, report, gate)
    report.print(include_output=True, include_reasons=True)
    return gate


def _write_evaluation_artifacts(
    run_root: Path,
    report: EvaluationReport[
        BeamBendingChangeEvalInput,
        BeamBendingChangeObservation,
        BeamBendingChangeEvalMetadata,
    ],
    gate: BeamBendingChangeEvalGate,
) -> None:
    run_root.mkdir(parents=True, exist_ok=True)
    (run_root / "evaluation_report.txt").write_text(
        report.render(include_output=True, include_reasons=True),
        encoding="utf-8",
    )
    summary = {
        "name": report.name,
        "experiment_metadata": report.experiment_metadata,
        **gate.model_dump(mode="json"),
        "cases": [
            {
                "name": case.name,
                "model_change_pass": (
                    case.assertions["model_change_pass"].value
                    if "model_change_pass" in case.assertions
                    else False
                ),
                "metrics": case.metrics,
                "labels": {key: value.value for key, value in case.labels.items()},
                "scores": {key: value.value for key, value in case.scores.items()},
                "task_duration": case.task_duration,
            }
            for case in report.cases
        ],
        "failures": [failure.name for failure in report.failures],
    }
    (run_root / "evaluation_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    (run_root / "gate.json").write_text(
        gate.model_dump_json(indent=2),
        encoding="utf-8",
    )


def _case_passed(case: object) -> int:
    assertions = getattr(case, "assertions", {})
    assertion = assertions.get("model_change_pass")
    evaluator_failures = getattr(case, "evaluator_failures", ())
    return int(
        assertion is not None and assertion.value is True and not evaluator_failures
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run the verified-seed Abaqus 2024 B31 bending change eval."
    )
    parser.add_argument("--run-root", type=Path, required=True)
    parser.add_argument("--source-run-dir", type=Path, required=True)
    parser.add_argument(
        "--model-provider",
        type=DeepSeekGateway,
        choices=list(DeepSeekGateway),
        default=DeepSeekGateway.OPENCODE_GO,
    )
    parser.add_argument("--model", default=DEEPSEEK_V4_FLASH)
    parser.add_argument("--http-retries", type=int, default=DEFAULT_MODEL_HTTP_RETRIES)
    parser.add_argument(
        "--convergence-mode",
        type=BeamBendingConvergenceMode,
        choices=list(BeamBendingConvergenceMode),
        default=BeamBendingConvergenceMode.OFF,
    )
    parser.add_argument("--repeat", type=int, default=3)
    parser.add_argument("--required-passes", type=int, default=2)
    args = parser.parse_args()
    gate = asyncio.run(
        run_evaluation(
            args.run_root,
            source_run_dir=args.source_run_dir,
            model_gateway=args.model_provider,
            model_name=args.model,
            http_retries=args.http_retries,
            repeat=args.repeat,
            required_passes=args.required_passes,
            convergence_mode=args.convergence_mode,
        )
    )
    raise SystemExit(0 if gate.passed else 1)


if __name__ == "__main__":
    main()
