DEFAULT_MODEL_CHANGE_TASK_INSTRUCTIONS = """
This is a verified existing-model requirement change, not a from-scratch plate
task. All physical inputs are complete, so do not return needs_input. Inspect
and modify the existing Python files required by the user goal. Preserve the
requested CAE -> INP, Solver -> ODB, and standalone odbAccess -> JSON stage
boundary; do not create results.json through the generic shell. The task is
complete only after the current artifacts have been generated by those three
typed Abaqus tools and you have inspected results.json. Then return
ready_for_verification. If the change cannot be supported by runtime evidence
within budget, return failed.
""".strip()


class _FrozenModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)


class ModelChangeRuntimeResult[AttemptT: VerificationAttempt](_FrozenModel):
    run_id: str
    workspace: Path
    outcome: CodingRunOutcome
    verification: AttemptT | None = None
    abaqus_runtime_seconds: float = Field(ge=0)


async def execute_model_change_case[AttemptT: VerificationAttempt](
    run_root: Path,
    *,
    seed: VerifiedModelSeed,
    goal: str,
    run_id_prefix: str,
    verifier: CodingRunVerifier[AttemptT],
    budget: CodingRunBudget,
    model_gateway: DeepSeekGateway,
    model_name: str,
    api_key: SecretStr,
    http_retries: int,
    api_catalog: ApiCatalog | None = None,
    api_catalog_mode: ApiCatalogMode = "off",
    concept_index: AbaqusDocumentIndex | None = None,
    diagnostic_retrieval_mode: DiagnosticRetrievalMode = "off",
    diagnostic_retrieval_instructions_enabled: bool | None = None,
    immutable_workspace_paths: tuple[str, ...] = (),
    runtime_script_policy: RuntimeScriptPolicy | None = None,
    probe_protocol_mode: ProbeProtocolMode = "off",
    probe_target_scripts: tuple[str, ...] | None = None,
    task_instructions: str = DEFAULT_MODEL_CHANGE_TASK_INSTRUCTIONS,
    verify_on_budget_exhaustion: bool = True,
) -> ModelChangeRuntimeResult[AttemptT]:
    _validate_api_catalog_configuration(api_catalog, api_catalog_mode)
    if diagnostic_retrieval_mode == "advisory" and concept_index is None:
        raise ValueError("diagnostic advisory requires a concept index")
    run_id = f"{run_id_prefix}-{uuid4().hex[:10]}"
    resolved = await create_seeded_workspace_async(run_root, run_id, seed)
    request = CodingRunRequest(
        run_id=run_id,
        goal=goal,
        workspace=resolved.workspace,
        state_dir=resolved.state_dir,
        runtime=RuntimeProfile(launcher_path=DEFAULT_ABAQUS_2024_LAUNCHER.resolve()),
        runtime_script_policy=runtime_script_policy or RuntimeScriptPolicy(),
        api_catalog=_api_catalog_binding(api_catalog),
        concept_index=(
            concept_index_binding(concept_index) if concept_index is not None else None
        ),
        **budget.as_request_controls(),
    )
    runner = Abaqus2024Runner(
        request.workspace,
        request.state_dir,
        launcher=request.runtime.launcher_path,
    )
    model, client = create_deepseek_chat_model(
        gateway=model_gateway,
        model_name=model_name,
        api_key=api_key,
        http_retries=http_retries,
        conversation_id=request.run_id
        if model_gateway is DeepSeekGateway.OPENCODE_GO
        else None,
    )
    dependencies = CodingAgentDependencies(
        request=request,
        runner=runner,
        api_catalog=api_catalog,
        concept_index=concept_index,
    )
    agent = create_abaqus_coding_agent(
        model,
        request,
        skill_library=skill_library_path(),
        api_catalog_mode=api_catalog_mode,
        concept_retrieval_mode="off",
        diagnostic_retrieval_mode=diagnostic_retrieval_mode,
        diagnostic_retrieval_instructions_enabled=(
            diagnostic_retrieval_instructions_enabled
        ),
        immutable_workspace_paths=immutable_workspace_paths,
        probe_protocol_mode=probe_protocol_mode,
        probe_target_scripts=probe_target_scripts,
        planning_enabled=False,
        task_instructions=task_instructions,
    )
    service = CodingRunService[AttemptT](
        agent=agent,
        request=request,
        dependencies=dependencies,
        clarification_provider=ScriptedClarificationProvider({}),
        verifier=verifier,
        initial_snapshot=resolved.initial_snapshot,
        verify_on_budget_exhaustion=verify_on_budget_exhaustion,
    )
    try:
        result = await service.run()
    finally:
        current = WorkspaceResolver(captured_cwd=request.workspace).snapshot(
            request.workspace
        )
        write_workspace_change_evidence(
            request.state_dir,
            resolved.initial_snapshot,
            current,
            source_run_id=seed.outcome.run_id,
            seed_texts=seed.seed_texts,
            workspace=request.workspace,
        )
        await client.close()
    return ModelChangeRuntimeResult[AttemptT](
        run_id=run_id,
        workspace=request.workspace,
        outcome=result.outcome,
        verification=result.verification,
        abaqus_runtime_seconds=sum(
            execution.duration_seconds for execution in dependencies.executions
        ),
    )


async def create_seeded_workspace_async(
    run_root: Path,
    run_id: str,
    seed: VerifiedModelSeed,
) -> ResolvedWorkspace:
    return await asyncio.to_thread(create_seeded_workspace, run_root, run_id, seed)


def _api_catalog_binding(catalog: ApiCatalog | None) -> ApiCatalogBinding | None:
    if catalog is None:
        return None
    manifest = catalog.manifest
    if manifest is None:
        raise ValueError("persisted API catalog is missing its manifest")
    return ApiCatalogBinding(
        schema_version=manifest.schema_version,
        cards_sha256=manifest.cards_sha256,
        card_count=manifest.card_count,
        member_count=manifest.member_count,
        members_sha256=manifest.members_sha256,
        runtime_release=manifest.runtime_release,
    )


def _validate_api_catalog_configuration(
    catalog: ApiCatalog | None,
    mode: ApiCatalogMode,
) -> None:
    if mode == "off" and catalog is not None:
        raise ValueError("off mode must not receive an API catalog")
    if mode != "off" and catalog is None:
        raise ValueError(f"{mode} mode requires an API catalog")
